  function pick(en, pl) {
    const lang = typeof KlyoI18n !== "undefined" ? KlyoI18n.getLang() : "en";
    return lang === "en"
      ? en
      : lang === "pl"
        ? pl || data[en]?.pl || en
        : data[en]?.[lang] || en;
  }
  const reverse = new Map();
  for (const [en, v] of Object.entries(data))
    for (const text of Object.values(v))
      if (!reverse.has(text)) reverse.set(text, en);
  const key = (en) => (data[en] ? en : reverse.get(en) || en);
  const esc = (v) =>
    String(v ?? "").replace(
      /[&<>"']/g,
      (c) =>
        ({
          "&": "&amp;",
          "<": "&lt;",
          ">": "&gt;",
          '"': "&quot;",
          "'": "&#39;",
        })[c],
    );
  function label(en, pl) {
    const original = key(en);
    return `<span data-module-key="${esc(original)}"${pl ? ' data-module-pl="' + esc(pl) + '"' : ""}>${esc(pick(original, pl))}</span>`;
  }
